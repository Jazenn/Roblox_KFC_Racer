local Model = require("../src/DriveModel")
local count = 0
local function check(condition, message)
    assert(condition, message)
    count = count + 1
end

for _, value in ipairs({0, -1, 1, 1e12}) do
    check(Model.finite(value), "finite control value rejected")
end
for _, value in ipairs({"1", true, {}, math.huge, -math.huge, 0 / 0}) do
    check(not Model.finite(value), "non-finite control value accepted")
end
check(not Model.finite(nil), "nil accepted")
check(Model.accept(1, 0, true, 1, -1, false), "valid driver rejected")
check(not Model.accept(1, 0, false, 0, 0, false), "non-driver accepted")
check(not Model.accept(math.huge, 0, true, 0, 0, false), "invalid clock accepted")
check(not Model.accept(1, 0 / 0, true, 0, 0, false), "invalid previous clock accepted")
check(not Model.accept(0.01, 0, true, 0, 0, false), "input flood accepted")
check(not Model.accept(0, 1, true, 0, 0, false), "backward clock accepted")
check(not Model.accept(1, 0, true, 0 / 0, 0, false), "NaN throttle accepted")
check(not Model.accept(1, 0, true, 0, "left", false), "string steering accepted")
check(not Model.accept(1, 0, true, 2, 0, false), "oversized throttle accepted")
check(not Model.accept(1, 0, true, 0, -2, false), "oversized steering accepted")
check(not Model.accept(1, 0, true, 0, 0, 1), "invalid handbrake accepted")
local target, torque, rearTarget, rearTorque, angle = Model.drive(0, 1, 1, false)
check(target == 78 and rearTarget == 78, "forward drive target")
check(torque == 8000 and rearTorque == torque and angle == 36, "gentler drive force with unchanged steering")
target, torque, rearTarget, rearTorque, angle = Model.drive(60, -1, -1, false)
check(target == 0 and torque == 24000, "reverse must brake while moving forward")
check(angle < 0 and math.abs(angle) < 36 and math.abs(angle) >= 28, "steering keeps useful lock at speed")
target = Model.drive(0, -1, 0, false)
check(target == -26, "reverse from rest")
target, torque = Model.drive(30, 0, 0, false)
check(target == 0 and torque == 100, "coasting must not apply full brakes")
target, torque, rearTarget, rearTorque = Model.drive(30, 1, 0, true)
check(target == 78 and rearTarget == 0 and rearTorque > torque, "handbrake must only lock rear")
check(Model.impact(80, 20, false) == "wreck", "severe impact")
check(Model.impact(80, 20, true) == "wreck", "damage must not suppress severe wreck")
check(Model.impact(45, 10, false) == "damage", "moderate impact")
check(Model.impact(45, 10, true) == "none", "do not detach repeated wheels")
check(Model.impact(20, 0, false) == "none", "small collision")
check(Model.impact(70, 65, false) == "none", "small velocity loss")
check(Model.impact(40, 12, false) == "none", "ordinary bump should remain driveable")
check(Model.impact(60, 10, false) == "damage", "medium-speed hard hit should not total the van")
check(Model.impact(78, 20, false) == "damage", "substantial speed retained should avoid a full wreck")
check(Model.impact(78, 70, false) == "none", "full-speed scratch should not shed parts")
check(not Model.canRecover(12.999, 10), "crash viewing must not be skippable")
check(Model.canRecover(13, 10), "recovery at three seconds")
assert(require("./steering.test"), "Steering regression suite did not complete")
assert(require("./impact.test"), "Impact regression suite did not complete")
print("PASS: " .. count .. " baseline driving, input-authority, damage and recovery assertions")
