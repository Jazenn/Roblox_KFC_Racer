local Model = require("../src/DriveModel")

local _, _, _, _, parkingAngle = Model.drive(0, 1, 1, false)
assert(parkingAngle >= 35, "Low-speed full lock must permit a tight turn")
local speed, torque, rearSpeed, rearTorque, fastAngle = Model.drive(78, 1, 1, false)
assert(fastAngle >= 28, "Full-speed hard steering must retain enough lock to risk tipping")
assert(speed == 78 and rearSpeed == 78, "Steering must not cut requested road speed")
assert(torque > 0 and rearTorque > 0, "Steering must retain drive torque")

local throttle, steering = Model.axes(true, false, false, true)
assert(throttle == 1 and steering == 1, "Key-down controls must apply full input immediately")
throttle, steering = Model.axes(false, true, true, false)
assert(throttle == -1 and steering == -1, "Brake/reverse and left steering")
throttle, steering = Model.axes(true, true, true, true)
assert(throttle == 0 and steering == 0, "Opposing keys must cancel")
throttle, steering = Model.axes(false, false, false, false)
assert(throttle == 0 and steering == 0, "Released keys must clear input immediately")

local innerAngle, innerFactor = Model.wheel(30, 3.65, false)
local outerAngle, outerFactor = Model.wheel(30, -3.65, false)
assert(innerAngle > 30 and outerAngle < 30, "Inner wheel must steer more sharply than outer wheel")
assert(innerFactor < outerFactor, "Inner wheel must roll slower to prevent tire scrub")
local rearAngle, rearFactor = Model.wheel(30, 3.65, true)
assert(rearAngle == 0 and rearFactor < 1, "Rear axle stays straight with differential road speed")
local mirrorAngle, mirrorFactor = Model.wheel(-30, -3.65, false)
assert(math.abs(mirrorAngle + innerAngle) < 0.001, "Left/right turns must mirror")
assert(math.abs(mirrorFactor - innerFactor) < 0.001, "Left/right speed factors must mirror")
local straightAngle, straightFactor = Model.wheel(0, 3.65, false)
assert(straightAngle == 0 and straightFactor == 1, "Straight driving must not introduce toe or speed bias")
print("PASS: 14 steering geometry, drive retention and immediate key-state assertions")
assert(Model.rollLoad(78, 1, true) > 0, "Fast hard right turn must load the outside wheels")
assert(Model.rollLoad(78, -1, true) < 0, "Fast hard left turn must mirror the roll load")
assert(Model.rollLoad(78, 1, false) == 0, "Airborne steering must never apply roll assistance")
assert(Model.rollLoad(30, 1, true) == 0, "Ordinary low-speed turns must remain stable")
assert(Model.rollLoad(78, 0.5, true) == 0, "Gentle fast steering must remain stable")
assert(Model.rollLoad(78, 0, true) == 0, "Straight driving must not apply roll torque")
assert(Model.rollLoad(55, 1, true) == 0, "Lower speeds must have zero extra roll load")
assert(Model.rollLoad(65, 1, true) == 0, "Moderate speed must not trigger extra tipping")
assert(Model.rollLoad(70, 1, true) < 0.2, "Roll assistance must build gently near its threshold")
assert(Model.rollLoad(-78, 1, true) == Model.rollLoad(78, 1, true), "Reverse hard turns share the same roll load")
print("PASS: 10 grounded rollover-boundary assertions")
local function heldTurn(speed, duration, steering)
    local exposure, load = 0, 0
    for _ = 1, math.floor(duration * 50 + 0.5) do
        exposure, load = Model.rollStep(exposure, speed, steering, true, 0.02)
    end
    return exposure, load
end
local briefRisk, briefLoad = heldTurn(78, 0.5, 1)
local sustainedRisk, sustainedLoad = heldTurn(78, 1.6, 1)
assert(briefLoad < 0.05, "Brief full-speed steering must not immediately apply tipping force")
assert(sustainedLoad > 0.9 and sustainedRisk > briefRisk, "Holding the hard turn must progressively build tipping force")
local slowerRisk, slowerLoad = heldTurn(70, 1.6, 1)
assert(slowerRisk < sustainedRisk and slowerLoad < briefLoad, "Lower speeds must build roll risk much more slowly")
local releasedRisk, releasedLoad = Model.rollStep(sustainedRisk, 78, 0, true, 0.1)
assert(releasedLoad == 0 and releasedRisk < sustainedRisk, "Releasing steering must clear force and drain accumulated risk")
local oppositeRisk, oppositeLoad = Model.rollStep(sustainedRisk, 78, -1, true, 0.02)
assert(oppositeRisk < 0 and oppositeLoad == 0, "Opposite turn must start a fresh buildup")
local airborneRisk, airborneLoad = Model.rollStep(sustainedRisk, 78, 1, false, 0.1)
assert(airborneLoad == 0 and airborneRisk < sustainedRisk, "Airborne motion must not retain active tipping force")
local zeroRisk, zeroLoad = Model.rollStep(-0.1, 0, 0, false, 0.1)
assert(zeroRisk == 0 and zeroLoad == 0, "Inactive risk must fully drain")
local unchangedRisk, unchangedLoad = Model.rollStep(0, 78, 1, true, -1)
assert(unchangedRisk == 0 and unchangedLoad == 0, "Negative elapsed time cannot create risk")
local cappedRisk = Model.rollStep(0, 78, 1, true, 100)
assert(cappedRisk < 0.1, "A stalled frame must not instantly fill the risk meter")
local leftRisk, leftLoad = heldTurn(78, 1.6, -1)
assert(math.abs(leftRisk + sustainedRisk) < 0.001 and math.abs(leftLoad + sustainedLoad) < 0.001, "Sustained turns must mirror left and right")
print("PASS: 10 sustained-turn buildup and decay assertions")
return true
